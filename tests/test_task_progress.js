const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const code = fs.readFileSync('static/index.js', 'utf8');
const start = code.indexOf('function estimatedTaskProgress(');
const context = {};
vm.runInNewContext(code.slice(start, code.indexOf('function appConfirm(', start)), context);
const task = {status:'generating', workflow_id:'a', width:768, height:768, steps:25, elapsed:30};
const sample = {id:'1', ...task, status:'completed', elapsed:60};
const calc = context.estimatedTaskProgress;
assert.equal(calc(task, [sample]).percent, 50);
assert.equal(calc({...task, elapsed:600, progress:{value:25,max:25}}, [sample]).percent, 99);
assert.equal(calc({...task,status:'completed'}, []).percent, 100);
assert.equal(calc(task, []).percent, null);
assert.equal(calc(task, [{...sample,workflow_id:'b'}]).percent, null);
assert.equal(calc(task, [sample,{...sample,id:'2',width:1024,elapsed:100}]).average, 60);
assert.equal(calc(task, [sample,sample,{...sample,id:'2',elapsed:120}]).average, 90);
assert.equal(calc(task, [{...sample,elapsed:0},{...sample,elapsed:NaN}]).percent, null);
assert.equal(/\bconfirm\(/.test(code), false);
console.log('Task progress: historical average, profile isolation, deduplication and 99% cap passed; no native confirm remains.');
